from fpdf import FPDF
from pathlib import Path

class PDFExporter:
    def __init__(self, brand_name="Snow Seasons Tech"):
        self.brand_name = brand_name

    def export_markdown_to_pdf(self, md_content: str, output_path: Path, title: str):
        # Create PDF instance
        pdf = FPDF()
        pdf.add_page()
        
        # Use a slightly smaller font and explicit width for header to be safe
        pdf.set_font("helvetica", "B", 16)
        # w=190 for A4 (210mm) minus margins (10mm each)
        pdf.cell(190, 10, title, ln=True, align="C")
        
        pdf.set_font("helvetica", "I", 10)
        pdf.cell(190, 10, f"Generated by {self.brand_name}", ln=True, align="C")
        pdf.ln(10)

        pdf.set_font("helvetica", "", 12)
        
        for line in md_content.split('\n'):
            line = line.strip()
            if not line:
                pdf.ln(5)
                continue
                
            if line.startswith('# '):
                pdf.set_font("helvetica", "B", 14)
                pdf.multi_cell(190, 10, line[2:])
                pdf.set_font("helvetica", "", 12)
            elif line.startswith('## '):
                pdf.set_font("helvetica", "B", 12)
                pdf.multi_cell(190, 10, line[3:])
                pdf.set_font("helvetica", "", 12)
            else:
                pdf.multi_cell(190, 10, line)

        pdf.output(str(output_path))
